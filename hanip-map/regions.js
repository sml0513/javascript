const regionAliases = new Map([
  ...nationalRegions.map(([name]) => [name,name]),
  ['서울','서울특별시'], ['부산','부산광역시'], ['대구','대구광역시'], ['인천','인천광역시'],
  ['대전','대전광역시'], ['울산','울산광역시'], ['세종','세종특별자치시'], ['경기','경기도'],
  ['강원도','강원특별자치도'], ['강원','강원특별자치도'], ['충북','충청북도'], ['충남','충청남도'],
  ['전라북도','전북특별자치도'], ['전북','전북특별자치도'],
  ['광주광역시','전남광주통합특별시'], ['광주','전남광주통합특별시'],
  ['전라남도','전남광주통합특별시'], ['전남','전남광주통합특별시'],
  ['전남광주특별시','전남광주통합특별시'], ['전남광주','전남광주통합특별시'],
  ['경북','경상북도'], ['경남','경상남도'], ['제주도','제주특별자치도'], ['제주','제주특별자치도']
]);

function regionOf(value) {
  return typeof value==='string' ? regionAliases.get(value.trim().split(/\s+/)[0]) : undefined;
}

function shopRegion(shop) {
  return regionOf(shop.region) || regionOf(shop.address) || '서울특별시';
}
